// Constraints such as ^1.0.0 are quoted, which YAML reads as the same string.
const pubspecYAMLAfter = `dependencies:
  flutter: any
  acme_auth: any
  acme_utils: any
  acme_hosted: '^2.0.0'
  http: '^1.0.0'
  plain: any
dev_dependencies:
  lints: '^3.0.0'
  mockito: '^5.4.0'
dependency_overrides:
  http: 1.2.0
  mockito: 5.4.4
`

func TestSanitizePubspecLock(t *testing.T) {
	sanitized, err := sanitizePubspecLock([]byte(pubspecLockBefore), nil)

	assert.NoError(t, err)
	assert.Equal(t, pubspecLockAfter, string(sanitized))
}

func TestSanitizePubspecLockWithNoPackages(t *testing.T) {
	sanitized, err := sanitizePubspecLock([]byte("packages: {}\nsdks:\n  dart: \">=3.2.0 <4.0.0\"\n"), nil)

	assert.NoError(t, err)
	assert.Equal(t, "packages: {}\n", string(sanitized))
}

func TestSanitizePubspecLockInvalid(t *testing.T) {
	for _, content := range []string{
		"",
		"just text",
		"sdks:\n  dart: any\n",
		"packages:\n  - async\n",
		"packages:\n  async: 2.11.0\n",
	} {
		_, err := sanitizePubspecLock([]byte(content), nil)
		assert.ErrorIs(t, err, util.ErrInvalidFormat, content)
	}
}

func TestSanitizePubspecYAML(t *testing.T) {
	sanitized, err := sanitizePubspecYAML([]byte(pubspecYAMLBefore), nil)

	assert.NoError(t, err)
	assert.Equal(t, pubspecYAMLAfter, string(sanitized))
	assert.NotContains(t, string(sanitized), "acme.internal")
}

func TestSanitizePubspecYAMLWithNoDependencies(t *testing.T) {
	sanitized, err := sanitizePubspecYAML([]byte("name: payments_portal\ndev_dependencies:\n"), nil)

	assert.NoError(t, err)
	assert.Equal(t, "dependencies: {}\n", string(sanitized))
}

func TestSanitizePubspecYAMLInvalid(t *testing.T) {
	for _, content := range []string{
		"",
		"- a list",
		"dependencies:\n  - http\n",
	} {
		_, err := sanitizePubspecYAML([]byte(content), nil)
		assert.ErrorIs(t, err, util.ErrInvalidFormat, content)
	}
}
