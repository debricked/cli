package cargo

import (
	"testing"

	"github.com/debricked/cli/internal/sanitize/pm/testdata"
	"github.com/debricked/cli/internal/sanitize/pm/util"
	"github.com/stretchr/testify/assert"
)

const cargoLockBefore = `# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 3

[[package]]
name = "acme-auth"
version = "2.1.0"
source = "git+ssh://git@git.acme.internal/platform/auth.git?tag=v2.1.0#9f3c1ab"

[[package]]
name = "acme-logger"
version = "1.4.2"
source = "registry+https://artifactory.acme.internal/api/cargo/index"
checksum = "aaaa"

[[package]]
name = "payments-portal"
version = "3.4.1"
dependencies = [
 "acme-auth",
 "acme-logger",
 "serde",
]

[[package]]
name = "serde"
version = "1.0.197"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "bbbb"
`

const cargoLockAfter = `[[package]]
name = "acme-auth"
version = "2.1.0"
source = "git+redacted"

[[package]]
name = "acme-logger"
version = "1.4.2"

[[package]]
name = "debricked-redacted-project-1"
version = "0.0.0"

[[package]]
name = "serde"
version = "1.0.197"

`

func TestSanitizeCargoLock(t *testing.T) {
	context, all := testdata.NewContext("Cargo.lock")

	sanitized, err := sanitizeCargoLock([]byte(cargoLockBefore), context)

	assert.NoError(t, err)
	assert.Equal(t, cargoLockAfter, string(sanitized))
	assert.Equal(t, []util.MapEntry{
		{Placeholder: "debricked-redacted-project-1", Name: "payments-portal", Path: "Cargo.lock"},
	}, all.Entries())
}

func TestSanitizeCargoLockInvalid(t *testing.T) {
	for _, content := range []string{
		"",
		"version = 3\n",
		"not toml at all [[\n",
		"[[package]]\nversion = \"1.0.0\"\n",
	} {
		context, _ := testdata.NewContext("Cargo.lock")
		_, err := sanitizeCargoLock([]byte(content), context)
		assert.ErrorIs(t, err, util.ErrInvalidFormat, content)
	}
}
