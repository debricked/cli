package godep

import (
	"testing"

	"github.com/debricked/cli/internal/sanitize/pm/util"
	"github.com/stretchr/testify/assert"
)

const gopkgLockBefore = `# This file is autogenerated, do not edit; changes may be undone by the next 'dep ensure'.

[[projects]]
  branch = "feature/PROJ-123"
  digest = "1:aaaa"
  name = "git.acme.internal/platform/authclient"
  packages = ["internal/secrets", "."]
  pruneopts = "UT"
  revision = "9f3c1ab"
  source = "ssh://git@git.acme.internal/platform/authclient.git"

[[projects]]
  digest = "1:bbbb"
  name = "github.com/pkg/errors"
  packages = ["."]
  pruneopts = "UT"
  revision = "cccc"
  version = "v0.9.1"

[solve-meta]
  analyzer-name = "dep"
  analyzer-version = 1
  input-imports = ["git.acme.internal/platform/authclient/internal/secrets"]
  solver-name = "gps-cdcl"
  solver-version = 1
`

const gopkgLockAfter = `[[projects]]
  name = "git.acme.internal/platform/authclient"

[[projects]]
  name = "github.com/pkg/errors"
  version = "v0.9.1"
`

func TestSanitizeGopkgLock(t *testing.T) {
	sanitized, err := sanitizeGopkgLock([]byte(gopkgLockBefore), nil)

	assert.NoError(t, err)
	assert.Equal(t, gopkgLockAfter, string(sanitized))
}

func TestSanitizeGopkgLockInvalid(t *testing.T) {
	for _, content := range []string{
		"",
		"[solve-meta]\n  solver-name = \"gps-cdcl\"\n",
		"[[projects]\n",
		"[[projects]]\n  version = \"v1.0.0\"\n",
	} {
		_, err := sanitizeGopkgLock([]byte(content), nil)
		assert.ErrorIs(t, err, util.ErrInvalidFormat, content)
	}
}
