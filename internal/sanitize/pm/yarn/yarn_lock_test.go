func TestSanitizeYarnLock(t *testing.T) {
	cases := map[string]struct{ before, after string }{
		"v1":    {testdata.YarnV1Before, testdata.YarnV1After},
		"berry": {testdata.YarnBerryBefore, testdata.YarnBerryAfter},
	}
	for name, c := range cases {
		t.Run(name, func(t *testing.T) {
			sanitized, err := sanitizeYarnLock([]byte(c.before), newTestContext("yarn.lock"))

			assert.NoError(t, err)
			assert.Equal(t, c.after, string(sanitized))
			assert.NotContains(t, string(sanitized), "#  ")
			assert.NotContains(t, string(sanitized), "autogenerated")
		})
	}
}

// A registry package with the project's name must keep its name, or the backend can't identify it.
func TestSanitizeYarnLockRenamesOnlyTheProjectDescriptors(t *testing.T) {
	const placeholder = "debricked-redacted-project-1"
	cases := map[string]struct{ before, after string }{
		"npm dependency with the project's name": {
			before: "\"lodash@npm:4.17.20\":\n  version: 4.17.20\n\n" +
				"\"lodash@workspace:.\":\n  version: 0.0.0-use.local\n  dependencies:\n    lodash: \"npm:4.17.20\"\n",
			after: "\"lodash@npm:4.17.20\":\n  version: 4.17.20\n\n" +
				"\"" + placeholder + "@workspace:.\":\n  version: 0.0.0-use.local\n  dependencies:\n    lodash: \"npm:4.17.20\"\n",
		},
		"transitive npm dependency with the project's name": {
			before: "\"debug@npm:^4.0.0\":\n  version: 4.3.4\n  dependencies:\n    ms: \"npm:2.1.2\"\n\n" +
				"\"ms@npm:2.1.2\":\n  version: 2.1.2\n\n" +
				"\"ms@workspace:.\":\n  version: 0.0.0-use.local\n  dependencies:\n    debug: \"npm:^4.0.0\"\n",
			after: "\"debug@npm:^4.0.0\":\n  version: 4.3.4\n  dependencies:\n    ms: \"npm:2.1.2\"\n\n" +
				"\"ms@npm:2.1.2\":\n  version: 2.1.2\n\n" +
				"\"" + placeholder + "@workspace:.\":\n  version: 0.0.0-use.local\n  dependencies:\n    debug: \"npm:^4.0.0\"\n",
		},
		"scoped project next to an unscoped package": {
			before: "\"@acme/lodash@workspace:.\":\n  version: 0.0.0-use.local\n  dependencies:\n    lodash: \"npm:4.17.20\"\n\n" +
				"\"lodash@npm:4.17.20\":\n  version: 4.17.20\n",
			after: "\"" + placeholder + "@workspace:.\":\n  version: 0.0.0-use.local\n  dependencies:\n    lodash: \"npm:4.17.20\"\n\n" +
				"\"lodash@npm:4.17.20\":\n  version: 4.17.20\n",
		},
		"other specs in the project's header": {
			before: "\"app@npm:^1.0.0, app@workspace:.\":\n  version: 0.0.0-use.local\n\n" +
				"\"member@workspace:packages/member\":\n  version: 0.0.0-use.local\n  dependencies:\n    app: \"npm:^1.0.0\"\n",
			after: "\"" + placeholder + "@npm:^1.0.0, " + placeholder + "@workspace:.\":\n  version: 0.0.0-use.local\n\n" +
				"\"member@workspace:redacted\":\n  version: 0.0.0-use.local\n  dependencies:\n    " + placeholder + ": \"npm:^1.0.0\"\n",
		},
	}
	for name, c := range cases {
		t.Run(name, func(t *testing.T) {
			sanitized, err := sanitizeYarnLock([]byte(c.before), newTestContext("yarn.lock"))

			assert.NoError(t, err)
			assert.Equal(t, c.after, string(sanitized))
		})
	}
}

func TestSanitizeYarnLockKeepsARedactedLocator(t *testing.T) {
	const rootLocator = "::locator=debricked-redacted-project-1%40workspace%3A."
	cases := map[string]struct{ before, after string }{
		"portal from the root": {
			before: "\"app@workspace:.\":\n  version: 0.0.0-use.local\n  dependencies:\n    shared: \"portal:../shared-utils\"\n\n" +
				"\"shared@portal:../shared-utils::locator=app%40workspace%3A.\":\n  version: 0.0.0-use.local\n",
			after: "\"debricked-redacted-project-1@workspace:.\":\n  version: 0.0.0-use.local\n  dependencies:\n    shared: \"file:./redacted\"\n\n" +
				"\"shared@file:./redacted" + rootLocator + "\":\n  version: 0.0.0-use.local\n",
		},
		"link from a workspace member": {
			before: "\"shared@link:../shared::locator=%40acme%2Fbench%40workspace%3Abenchmark\":\n  version: 0.0.0-use.local\n",
			after:  "\"shared@file:./redacted::locator=%40acme%2Fbench%40workspace%3Aredacted\":\n  version: 0.0.0-use.local\n",
		},
		"bindings without a locator": {
			before: "\"shared@exec:./gen.js::hash=abc\":\n  version: 1.0.0\n",
			after:  "\"shared@file:./redacted\":\n  version: 1.0.0\n",
		},
	}
	for name, c := range cases {
		t.Run(name, func(t *testing.T) {
			sanitized, err := sanitizeYarnLock([]byte(c.before), newTestContext("yarn.lock"))

			assert.NoError(t, err)
			assert.Equal(t, c.after, string(sanitized))
		})
	}
}

// Masking turns different paths into the same placeholder, so without the locator two blocks
// would get the same header, and the backend never finishes processing the file.
func TestSanitizeYarnLockKeepsHeadersOfTheSamePackageApart(t *testing.T) {
	content := "\"babel@workspace:.\":\n  version: 0.0.0-use.local\n\n" +
		"\"utils@link:../scripts/utils::locator=%40babel%2Fbench%40workspace%3Abenchmark\":\n  version: 0.0.0-use.local\n\n" +
		"\"utils@link:./scripts/utils::locator=babel%40workspace%3A.\":\n  version: 0.0.0-use.local\n"

	sanitized, err := sanitizeYarnLock([]byte(content), newTestContext("yarn.lock"))

	assert.NoError(t, err)
	headers := map[string]bool{}
	for _, line := range strings.Split(string(sanitized), "\n") {
		if strings.HasPrefix(line, "\"") {
			assert.False(t, headers[line], "duplicate header %s", line)
			headers[line] = true
		}
	}
	assert.Len(t, headers, 3)
	assert.NotContains(t, string(sanitized), "locator=babel")
	assert.NotContains(t, string(sanitized), "scripts")
}

func TestSanitizeYarnLockRemovesInlineCommentLines(t *testing.T) {
	content := "# top\nfoo@^1.0.0:\n  # indented s3cret comment\n  version \"1.0.0\"\n"

	sanitized, err := sanitizeYarnLock([]byte(content), newTestContext("yarn.lock"))

	assert.NoError(t, err)
	assert.Equal(t, "foo@^1.0.0:\n  version \"1.0.0\"\n", string(sanitized))
}

func TestSanitizeYarnLockCRLF(t *testing.T) {
	content := "foo@^1.0.0:\r\n  version \"1.0.0\"\r\n"

	sanitized, err := sanitizeYarnLock([]byte(content), newTestContext("yarn.lock"))

	assert.NoError(t, err)
	assert.Equal(t, "foo@^1.0.0:\n  version \"1.0.0\"\n", string(sanitized))
}

func TestSanitizeYarnLockInvalid(t *testing.T) {
	invalid := map[string]string{
		"not a lock file":      "this is not a lock file\n",
		"header without @":     "foo:\n  version \"1.0.0\"\n",
		"entry before a block": "  version \"1.0.0\"\n",
		"odd indentation":      "foo@^1.0.0:\n   version \"1.0.0\"\n",
	}
	for name, content := range invalid {
		t.Run(name, func(t *testing.T) {
			_, err := sanitizeYarnLock([]byte(content), newTestContext("yarn.lock"))
			assert.ErrorIs(t, err, util.ErrInvalidFormat)
		})
	}
}

func newTestContext(path string) *util.FileContext {
	context, _ := testdata.NewContext(path)

	return context
}
