package yarn

import (
	"testing"

	"github.com/stretchr/testify/assert"

	"github.com/debricked/cli/internal/sanitize/pm/testdata"
	"github.com/debricked/cli/internal/sanitize/pm/util"
)

func TestSanitizeYarnLock(t *testing.T) {
	cases := map[string]struct{ before, after string }{
		"v1":    {testdata.YarnV1Before, testdata.YarnV1After},
		"berry": {testdata.YarnBerryBefore, testdata.YarnBerryAfter},
	}
	for name, c := range cases {
		t.Run(name, func(t *testing.T) {
			sanitized, err := sanitizeYarnLock([]byte(c.before), newTestContext("yarn.lock"))

			assert.NoError(t, err)
			assert.Equal(t, c.after, string(sanitized))
			assert.NotContains(t, string(sanitized), "#  ")
			assert.NotContains(t, string(sanitized), "autogenerated")
		})
	}
}

func TestSanitizeYarnLockRemovesInlineCommentLines(t *testing.T) {
	content := "# top\nfoo@^1.0.0:\n  # indented s3cret comment\n  version \"1.0.0\"\n"

	sanitized, err := sanitizeYarnLock([]byte(content), newTestContext("yarn.lock"))

	assert.NoError(t, err)
	assert.Equal(t, "foo@^1.0.0:\n  version \"1.0.0\"\n", string(sanitized))
}

func TestSanitizeYarnLockCRLF(t *testing.T) {
	content := "foo@^1.0.0:\r\n  version \"1.0.0\"\r\n"

	sanitized, err := sanitizeYarnLock([]byte(content), newTestContext("yarn.lock"))

	assert.NoError(t, err)
	assert.Equal(t, "foo@^1.0.0:\n  version \"1.0.0\"\n", string(sanitized))
}

func TestSanitizeYarnLockInvalid(t *testing.T) {
	invalid := map[string]string{
		"not a lock file":      "this is not a lock file\n",
		"header without @":     "foo:\n  version \"1.0.0\"\n",
		"entry before a block": "  version \"1.0.0\"\n",
		"odd indentation":      "foo@^1.0.0:\n   version \"1.0.0\"\n",
	}
	for name, content := range invalid {
		t.Run(name, func(t *testing.T) {
			_, err := sanitizeYarnLock([]byte(content), newTestContext("yarn.lock"))
			assert.ErrorIs(t, err, util.ErrInvalidFormat)
		})
	}
}

func newTestContext(path string) *util.FileContext {
	context, _ := testdata.NewContext(path)

	return context
}
